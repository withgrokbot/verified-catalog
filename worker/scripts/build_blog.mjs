#!/usr/bin/env node
// 0.39.0: render the markdown posts in /workspace/content/blog (or BLOG_DIR / argv[2]) to static HTML strings in
// worker/src/blog-data.js. Build time only: the Worker serves bundled strings (no KV, no I/O).
// Editorial-only parts are not published: HTML comments, and a trailing "---" + "**Alternative headlines**" block.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2] || process.env.BLOG_DIR || "/workspace/content/blog";
const out = join(here, "..", "src", "blog-data.js");

export const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
function inline(t) {
  const codes = [];
  t = t.replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`);
  t = esc(t);
  t = t.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, txt, href) => /^(https?:\/\/|\/|#)/.test(href.replace(/&amp;/g, "&")) ? `<a href="${href}">${txt}</a>` : txt);
  t = t.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>").replace(/(^|[^*\w])\*([^*\s][^*]*)\*(?!\w)/g, "$1<em>$2</em>");
  return t.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${esc(codes[Number(i)])}</code>`);
}
export function renderMarkdown(md) {
  md = md.replace(/<!--[\s\S]*?-->/g, "").replace(/\n---\s*\n+\*\*Alternative headlines\*\*[\s\S]*$/i, "\n");
  const L = md.replace(/\r\n/g, "\n").split("\n"), html = [];
  let i = 0;
  const isBlockStart = (l) => /^(#{1,6} |```|[-*] |\d+\. |\||---\s*$|> )/.test(l);
  while (i < L.length) {
    const l = L[i];
    if (!l.trim()) { i++; continue; }
    let m;
    if ((m = l.match(/^```(\w*)/))) {
      const buf = []; i++;
      while (i < L.length && !/^```/.test(L[i])) buf.push(L[i++]);
      i++;
      html.push(`<pre><code${m[1] ? ` class="lang-${esc(m[1])}"` : ""}>${esc(buf.join("\n"))}</code></pre>`);
    } else if ((m = l.match(/^(#{1,6}) (.*)$/))) {
      const n = m[1].length, id = m[2].toLowerCase().replace(/<[^>]+>|[`*]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
      html.push(`<h${n} id="${id}">${inline(m[2])}</h${n}>`); i++;
    } else if (/^---\s*$/.test(l)) { html.push("<hr>"); i++; }
    else if (/^\|/.test(l)) {
      const rows = []; while (i < L.length && /^\|/.test(L[i])) rows.push(L[i++]);
      const cells = (r) => r.trim().replace(/^\||\|$/g, "").split("|").map((c) => c.trim());
      const al = rows[1] && /^[\s|:-]+$/.test(rows[1]) ? cells(rows[1]).map((c) => (/:$/.test(c) ? "right" : "")) : [];
      const head = cells(rows[0]), body = rows.slice(al.length ? 2 : 1).map(cells);
      const td = (t, c, j) => `<${t}${al[j] ? ' class="r"' : ""}>${inline(c)}</${t}>`;
      html.push(`<table><thead><tr>${head.map((c, j) => td("th", c, j)).join("")}</tr></thead><tbody>${body.map((r) => `<tr>${r.map((c, j) => td("td", c, j)).join("")}</tr>`).join("")}</tbody></table>`);
    } else if (/^[-*] /.test(l) || /^\d+\. /.test(l)) {
      const ol = /^\d+\. /.test(l), re = ol ? /^\d+\. / : /^[-*] /, items = [];
      while (i < L.length && re.test(L[i])) { let t = L[i++].replace(re, ""); while (i < L.length && /^\s{2,}\S/.test(L[i])) t += " " + L[i++].trim(); items.push(t); }
      html.push(`<${ol ? "ol" : "ul"}>${items.map((t) => `<li>${inline(t)}</li>`).join("")}</${ol ? "ol" : "ul"}>`);
    } else if (/^> /.test(l)) {
      const buf = []; while (i < L.length && /^> ?/.test(L[i])) buf.push(L[i++].replace(/^> ?/, ""));
      html.push(`<blockquote><p>${inline(buf.join(" "))}</p></blockquote>`);
    } else {
      const buf = []; while (i < L.length && L[i].trim() && !isBlockStart(L[i])) buf.push(L[i++].trim());
      html.push(`<p>${inline(buf.join(" "))}</p>`);
    }
  }
  return html.join("\n");
}
export function parsePost(file, text) {
  const fm = {}; let body = text;
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (m) { body = text.slice(m[0].length); for (const line of m[1].split("\n")) { const k = line.match(/^(\w+):\s*(.*)$/); if (k) fm[k[1]] = k[2].replace(/^"(.*)"$/, "$1"); } }
  const d = file.match(/^(\d{4}-\d\d-\d\d)-(.+)\.md$/);
  return { slug: d ? d[2] : file.replace(/\.md$/, ""), date: d ? d[1] : null, title: fm.title || "", description: fm.meta_description || "", html: renderMarkdown(body) };
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const posts = readdirSync(dir).filter((f) => f.endsWith(".md")).sort().reverse().map((f) => parsePost(f, readFileSync(join(dir, f), "utf8")));
  writeFileSync(out, "// Generated by worker/scripts/build_blog.mjs from content/blog (do not edit by hand).\nexport const BLOG_POSTS = " + JSON.stringify(posts, null, 1) + ";\n");
  console.log(`wrote ${out}: ${posts.length} posts: ${posts.map((p) => p.slug).join(", ")}`);
}
