// 0.59.0 fix: writes src/verify-core-src.js, the verifier core as a STATIC string literal. verify.js emits that string
// into /verify.js, the standalone HTML and verify-receipt.mjs. It used to call verifierCore.toString() at runtime, but
// the deployed bundle's function text is the bundler's output (wrangler/esbuild inject __name(...) helpers), which
// broke the browser copy. A string literal is never rewritten by the bundler. Regenerate after editing
// src/verify-core.js:  node worker/scripts/gen-verify-core.mjs   (tests/verify_bundle_test.mjs fails if it is stale).
import { writeFileSync } from "node:fs";
import { verifierCore } from "../src/verify-core.js";

export const render = () => `// GENERATED by worker/scripts/gen-verify-core.mjs from src/verify-core.js. Do not edit by hand.
// The verifier core as a static string so bundling cannot alter the code shipped to browsers and Node.
export const VERIFIER_CORE_SRC = ${JSON.stringify(verifierCore.toString())};
`;
if (process.argv[1] && import.meta.url === new URL("file://" + process.argv[1]).href) {
  writeFileSync(new URL("../src/verify-core-src.js", import.meta.url), render());
}
