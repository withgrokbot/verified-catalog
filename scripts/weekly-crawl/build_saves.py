"""0.35.0 (flag SAVES_PAGE, off): /saves data from the stored crawl. A "save" is a real skip where the live 402 differed
from the listing: a different network, a different pay_to, or a price above the listing (>1%). Endpoint without query,
plain "what differed" (wallets never printed), date, receipt link. Excludes path templates, our own hosts, >30 days.
Writes app/worker/src/saves-data.js (newest SAVES_MAX rows + totals). Live D1 receipts are merged by the Worker."""
import json, os, re, sys, datetime as dt
HERE = os.path.dirname(os.path.abspath(__file__))
JOB = os.environ.get("BM_JOB") or os.path.abspath(os.path.join(HERE, "..", ".."))
R = os.path.join(JOB, "receipts")
OUT = os.path.join(JOB, "app", "worker", "src", "saves-data.js")
SAVES_MAX, MAX_AGE_D, TOL = 1000, 30, 0.01
OWN = re.compile(r"(^|\.)(402xagent\.com|payscout\.dev|withgrokbot\.workers\.dev|target\.test)$", re.I)
TEMPLATE = re.compile(r"(\{[^}/]*\}|/:[A-Za-z_]|\[[^\]/]*\]|%7B|%7D)", re.I)

def endpoint(u):
    m = re.match(r"^(https?)://([^/?#]+)([^?#]*)", str(u or ""))
    return (m.group(1) + "://" + m.group(2).lower() + (m.group(3) or "/")) if m else None

def money(x): return "$" + (f"{x:.6f}".rstrip("0").rstrip("."))

def crawl_save(r, now):
    if r.get("verdict") != "skip": return None
    u = endpoint(r.get("url")); reason = str(r.get("reason") or "")
    if not u or TEMPLATE.search(u): return None
    host = u.split("/")[2].split(":")[0]
    if OWN.search(host): return None
    ts = r.get("timestamp") or ""
    try: age = (now - dt.datetime.fromisoformat(ts.replace("Z", "+00:00"))).days
    except Exception: return None
    if age > MAX_AGE_D: return None
    if reason.startswith("asks a different price than listed"):
        a, q = r.get("claimed_price_usd"), r.get("quoted_price_usd")
        if a is None or q is None or not (float(q) > float(a) * (1 + TOL) + 1e-9): return None
        kind, what = "price_higher", f"asked {money(float(q))}, listed {money(float(a))}"
    elif reason.startswith("pays a different wallet than listed"):
        kind, what = "pay_to_changed", "pays a different wallet"
    elif reason.startswith("asks for payment on a different network than listed"):
        m = re.search(r"\(listed ([^,]+), offers ([^)]+)\)", reason)
        kind, what = "network_changed", (f"asks for payment on {m.group(2)}, listed {m.group(1)}" if m else "asks for payment on a different network")
    else:
        return None
    return {"endpoint": u, "kind": kind, "what": what, "date": ts[:10], "at": ts, "source": "crawl", "receipt_id": r.get("id")}

def main():
    now = dt.datetime.now(dt.timezone.utc)
    p = os.path.join(R, open(os.path.join(R, "latest.txt")).read().strip())
    rows, seen = [], set()
    for l in open(p):
        s = crawl_save(json.loads(l), now)
        if s and s["endpoint"] not in seen: seen.add(s["endpoint"]); rows.append(s)
    rows.sort(key=lambda x: x["at"], reverse=True)
    counts = {k: sum(1 for x in rows if x["kind"] == k) for k in ("price_higher", "pay_to_changed", "network_changed")}
    meta = {"built_at": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "crawl_file": os.path.basename(p), "total": len(rows), "counts": counts, "kept": min(len(rows), SAVES_MAX), "max_age_days": MAX_AGE_D}
    open(OUT, "w").write("// generated by scripts/weekly-crawl/build_saves.py (do not edit)\nexport const SAVES_META = " + json.dumps(meta, separators=(",", ":")) + ";\nexport const SAVES = " + json.dumps([{k: v for k, v in x.items() if k != "at"} for x in rows[:SAVES_MAX]], separators=(",", ":")) + ";\n")
    print(json.dumps(meta))
    return rows

if __name__ == "__main__":
    main()
