// 0.58.6: paragraph map for the /docs split. Every block (line) of the legacy single /docs page, and the page(s) that
// now carry it verbatim; wording fixes are listed as old -> new. Exit 1 if any block is missing.
// Usage: node scripts/docs_paragraph_map.mjs [out.md]
import { writeFileSync } from "node:fs";
import { legacyDocsParts, docsIndexHtml, docsProductHtml, DOCS_PAGES, DOCS_WORDING, DOCS_ANCHOR_MAP } from "../worker/src/docs.js";
import { CANON_ORIGIN, API_ORIGIN } from "../worker/src/spotcheck.js";

const OPTS = { endpointReport: true, watchtower: true, tryIt: { freePerDay: 5 } };
const { body } = legacyDocsParts(CANON_ORIGIN, API_ORIGIN, OPTS);
const pages = { "/docs": docsIndexHtml(CANON_ORIGIN, API_ORIGIN, OPTS) };
for (const p of DOCS_PAGES) pages["/docs/" + p.slug] = docsProductHtml(CANON_ORIGIN, API_ORIGIN, p.slug, OPTS);
const strip = (s) => s.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
const short = (s) => { const t = strip(s); return (t.length > 110 ? t.slice(0, 107) + "..." : t).replace(/\|/g, "\\|") || "(markup: " + s.slice(0, 40).replace(/\|/g, "\\|").replace(/</g, "&lt;") + ")"; };
const lines = body.split("\n").filter((l) => l.trim());
let missing = 0, changed = 0, n = 0;
const rows = [], diffs = [];
let section = "(intro)";
for (const l of lines) {
  const h = l.match(/<h2 id="([a-z-]+)">/); if (h) section = h[1];
  n++;
  let line = l, where = Object.keys(pages).filter((k) => pages[k].includes(line));
  if (!where.length) {
    const fixed = DOCS_WORDING.reduce((s, [a, b]) => s.split(a).join(b), l);
    if (fixed !== l) { where = Object.keys(pages).filter((k) => pages[k].includes(fixed)); if (where.length) { changed++; diffs.push(`- ${strip(l)}\n+ ${strip(fixed)}\n  (on ${where.join(", ")})`); } }
    if (l === "<h1>Docs</h1>") where = ["/docs (page h1 \"Docs\")"];
  }
  if (!where.length) missing++;
  rows.push(`| ${n} | ${section} | ${short(l)} | ${where.length ? where.join(", ") : "**MISSING**"}${where.length && line !== l ? "" : ""} |`);
}
const md = `# /docs paragraph map, 0.58.5 -> 0.58.6

Source: the legacy single-page generator \`docsHtml\` (worker/src/pages.js, unchanged), rendered with Endpoint Report and
Watchtower on. Each non-empty block line of its body, and the 0.58.6 page(s) that carry it **verbatim**. Generated by
\`node scripts/docs_paragraph_map.mjs\`; enforced by tests/docs_split_test.mjs.

Blocks: ${n}. Missing: ${missing}. Changed by the listed wording fixes: ${changed}. Everything else is byte-for-byte.

## Wording fixes (docs only; llms.txt, openapi.json and /.well-known/* unchanged)

\`\`\`diff
${diffs.join("\n")}
\`\`\`

## Old anchors (all still present on /docs as an element with the same id)

| old /docs#id | now | on /docs |
|---|---|---|
${Object.entries(DOCS_ANCHOR_MAP).map(([k, v]) => `| #${k} | ${v} | ${v.startsWith("/docs#") ? "the section itself" : "visible \"Moved to\" pointer; /docs/anchors.js forwards"} |`).join("\n")}

## Block map

| # | legacy section | block (text) | now on |
|---|---|---|---|
${rows.join("\n")}

## Added on the new pages (not in the legacy page)

- /docs: "Product docs" cards (one per product page plus the Audit layer on npm) and the "Moved sections" pointers.
- /docs/check: a Reason codes table (from the rules constants) linking /rules and /rules.json.
- /docs/receipt-verification: a link to a stored signed live-check receipt (${"/v1/receipts/sc-85c8963fb57e7b25"}).
- Every product page: sidebar, and a "Next step" link (its /pricing row, or the example receipt) plus the next page.
`;
const out = process.argv[2];
if (out) writeFileSync(out, md); else process.stdout.write(md);
console.error(`blocks ${n}, missing ${missing}, wording-changed ${changed}`);
process.exit(missing ? 1 : 0);
